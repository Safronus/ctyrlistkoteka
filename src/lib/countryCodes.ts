/** Alpha-2 for a Natural Earth numeric country id, or null when unmapped. */
export function alpha2FromNumeric(numeric: string): string | null {
  return ALPHA2_BY_NUMERIC[numeric] ?? null;
}

/**
 * Flag emoji for an alpha-2 code, built from the two regional-indicator code
 * points. Renders as a flag on macOS / iOS / Android; Windows has no flag
 * glyphs in its emoji font and shows the letter pair instead — accepted
 * trade-off (the owner's call) versus shipping SVG flag assets.
 */
export function countryFlagEmoji(alpha2: string): string | null {
  if (!/^[A-Za-z]{2}$/.test(alpha2)) return null;
  const base = 0x1f1e6;
  const [a, b] = alpha2.toUpperCase();
  return (
    String.fromCodePoint(base + a!.charCodeAt(0) - 65) +
    String.fromCodePoint(base + b!.charCodeAt(0) - 65)
  );
}
